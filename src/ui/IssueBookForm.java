    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
        
        String studentId = txtStudentId.getText();
    String bookId = txtBookId.getText();
    
    SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
    String issue = sdf.format(issueDate.getDate());
    String due = sdf.format(dueDate.getDate());
    String status = "Issued";

    try {
        Connection con = ConnectionProvider.getCon();
        PreparedStatement pst = con.prepareStatement(
            "INSERT INTO issued_books (studentId, bookId, issueDate, returnDate, status) VALUES (?, ?, ?, ?, ?)"
        );
        pst.setString(1, studentId);
        pst.setString(2, bookId);
        pst.setString(3, issue);
        pst.setString(4, due);
        pst.setString(5, status);

        pst.executeUpdate();
        JOptionPane.showMessageDialog(null, "✅ Book issued successfully!");

        txtStudentId.setText("");
        txtBookId.setText("");
        issueDate.setDate(null);
        dueDate.setDate(null);

    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "❌ Error: " + e.getMessage());
    }
    }//GEN-LAST:event_btnSaveActionPerformed

