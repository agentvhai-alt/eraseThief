    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        // TODO add your handling code here:
        String studentId = txtStudentId.getText();
    String bookId = txtBookId.getText();

    try {
        Connection con = ConnectionProvider.getCon();
        PreparedStatement pst = con.prepareStatement(
            "SELECT issueDate, returnDate FROM issued_books " +
            "WHERE studentId = ? AND bookId = ? AND status = 'Issued'"
        );
        pst.setString(1, studentId);
        pst.setString(2, bookId);
        ResultSet rs = pst.executeQuery();

        if (rs.next()) {
            txtIssueDate.setText(rs.getString("issueDate"));
            txtDueDate.setText(rs.getString("returnDate")); // returnDate আগে মানে dueDate
        } else {
            JOptionPane.showMessageDialog(null, "❌ No issued book found!");
            txtIssueDate.setText("");
            txtDueDate.setText("");
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "❌ Error: " + e.getMessage());
    }
    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
        String studentId = txtStudentId.getText();
    String bookId = txtBookId.getText();

    try {
        Connection con = ConnectionProvider.getCon();
        PreparedStatement pst = con.prepareStatement(
            "UPDATE issued_books SET status = 'Returned', returnDate = CURDATE() " +
            "WHERE studentId = ? AND bookId = ? AND status = 'Issued'"
        );
        pst.setString(1, studentId);
        pst.setString(2, bookId);

        int updated = pst.executeUpdate();
        if (updated > 0) {
            JOptionPane.showMessageDialog(null, "✅ Book returned successfully!");
            txtStudentId.setText("");
            txtBookId.setText("");
            txtIssueDate.setText("");
            txtDueDate.setText("");
        } else {
            JOptionPane.showMessageDialog(null, "⚠️ No matching issued book found!");
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "❌ Error: " + e.getMessage());
    }
    }//GEN-LAST:event_btnSaveActionPerformed

